"""Run the everyday-language queries through the intake gate once and save its specs (issue #20).

    python -m eval.gate_specs            # one gate request per query not yet saved
    CAD_GATE_PICKS=1 CAD_GATE_MODEL=gemini-3.5-flash-lite python -m eval.gate_specs --out eval/retrieval_queries_gate_lite_picks.json
                                         # also save the gate's example picks and shape summary

In the app, retrieval runs on the gate's spec (a geometric restatement of the request), not on the
user's words. This saves those specs to eval/retrieval_queries_gate.json so
`python -m eval.retrieval --queries gate` can score retrieval on them offline, repeatably.
Already-saved queries are skipped, so a run cut short by quota can be resumed.
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

EVAL_DIR = Path(__file__).parent
CASUAL_PATH = EVAL_DIR / "retrieval_queries_casual.json"
GATE_PATH = EVAL_DIR / "retrieval_queries_gate.json"


def gate_model() -> str:
    from stl_agent import pipeline

    return getattr(getattr(pipeline._gate, "llm", None), "model", "unknown")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=GATE_PATH)
    args = ap.parse_args(argv)
    from stl_agent.pipeline import run_gate

    casual = json.loads(CASUAL_PATH.read_text())
    out = json.loads(args.out.read_text()) if args.out.exists() else {
        "about": "Intake-gate specs for the everyday-language queries in retrieval_queries_casual.json, "
                 "generated by eval/gate_specs.py. Used by `python -m eval.retrieval --queries gate`.",
        "specs": {}}
    for cid, query in casual["queries"].items():
        if cid in out["specs"] and out["specs"][cid]["query"] == query:
            continue  # already done for this exact wording
        try:
            d = run_gate([{"role": "user", "content": query}], 0)
        except Exception as e:  # quota etc.: keep what we have, resume later
            print(f"stopping at {cid}: {type(e).__name__}: {e}")
            break
        out["specs"][cid] = {"query": query, "spec": d.spec, "action": d.action, "scope": d.scope, "gate_model": gate_model(),
                             "shape": d.shape, "examples": d.example_ids,
                             "generated": time.strftime("%Y-%m-%dT%H:%M:%S")}
        print(f"{cid} [{d.action}] picks={d.example_ids} shape={d.shape!r}")
        args.out.write_text(json.dumps(out, indent=1) + "\n")  # save after each, so nothing is lost
    print(f"\n{len(out['specs'])}/{len(casual['queries'])} specs in {args.out}")


if __name__ == "__main__":
    main()
